// Ejemplo: arreglo fijo y acceso por indice
#include <iostream>
using namespace std;

int main() {
    int notas[4];

    notas[0] = 8;
    notas[1] = 9;
    notas[2] = 7;
    notas[3] = 6;

    cout << "Nota 1: " << notas[0] << endl;
    cout << "Nota 2: " << notas[1] << endl;
    cout << "Nota 3: " << notas[2] << endl;
    cout << "Nota 4: " << notas[3] << endl;
    return 0;
}